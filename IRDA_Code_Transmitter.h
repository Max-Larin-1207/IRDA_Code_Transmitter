/*********************************************************************************************************************************************
 * IRDA_Code_Transmitter.h
 * Заголовочный файл драйвера генератора ИК-сигнала по протоколу NEC (эмуляция пульта ДУ)
 * Программная среда: STM32CubeIDE
 * Автор: Максимус Великолепный, =MxL=
 * Компания: Вертикаль, она же «Палитра»
 * Дата создания: 27 июля 2026
 * Драйвер написан без использования дебильной библиотеки HAL, непосредственно на регистрах
 ********************************************************************************************************************************************/

#ifndef IRDA_CODE_TRANSMITTER_H_
#define IRDA_CODE_TRANSMITTER_H_

#include "main.h"		// Подключение глобальной библиотеки

/*********************************************************************************************************************************************
 * Драйвер активируется, если он разрешён программой IR_TRANSMITTER_EN, а также определён таймер IRDA_TIMER и выход IR_TX_OUT_Pin
 * Выход ИК-передатчика должен быть именован как IR_TX_OUT и настроен на push-pull режим (или альтернативную функцию ШИМ).
 * Если нужно, чтобы драйвер настроил выход IR_TX_OUT без использования HAL-дури самостоятельно, то установить IR_TRASMIT_GPIO_DR_INIT_EN
 * Для синхронизации использован 16-битный базовый таймер (с минимальным набором функций).
 * В конфигуратор проекта MX добавлять (генерировать) прерывание таймера не нужно, драйвер настраивает таймер самостоятельно.
 * Для собственной инициализации периферии используется функция IR_Transmitter_Init ();
 * Для передачи кода используется функция IR_Transmitter_Send (uint32_t address, uint32_t command, bool repeat);
 ********************************************************************************************************************************************/
#ifndef IR_TRANSMITTER_EN
#define IR_TRANSMITTER_EN			0	// Разрешение работы драйвера ИК-передатчика
#endif
#ifndef IR_TRASMIT_OUT_POLAR_MODE
#define IR_TRASMIT_OUT_POLAR_MODE	0	// Режим полярности выхода: 0 - прямой выход, работа на ИК-светодиод, 1 - инвертированный выход
#endif
#ifndef IR_TRASMIT_GPIO_DR_INIT_EN
#define IR_TRASMIT_GPIO_DR_INIT_EN	0	// Инициализация выхода IR_TX_OUT драйвером
#endif
#ifndef IR_TRASMIT_CODE_16BIT_MODE
#define IR_TRASMIT_CODE_16BIT_MODE	0	// Режим кода: 0 - 8 битный, только прямая, 1 - 16 битный, прямая и инвертирующая составляющая вместе
#endif

// Интервал автоповтора (от начала стартового импульса до начала следующего):
#ifndef IR_REPEAT_INTERVAL_MS
#define IR_REPEAT_INTERVAL_MS		110		// 110 мс - стандарт NEC
#endif


/*********************************************************************************************************************************************
 * В основной программе нужно задать номер свободного 16-битного базового таймера IRDA_TIMER.
 * Драйвер настраивает таймер самостоятельно:
 * Режим счёта - вверх.
 * Прескаляр таймера настроен автоматически, в зависимости от тактовой частоты МК, на значение 1 мкс.
 * Рекомендуемый приоритет прерывания таймера IRDA_TIMER_IRQ_PRIORITY: 1 (0 - найвысший приоритет системы)
 * В вектор общих прерываний добавлять ничего не нужно! Драйвер автоматически настраивает NVIC и подтягивает функцию прерывания таймера.
 ********************************************************************************************************************************************/
#if IR_TRANSMITTER_EN && defined (IRDA_TIMER)
#ifndef IRDA_TIMER_IRQ_PRIORITY
#define IRDA_TIMER_IRQ_PRIORITY		1	// Приоритет прерывания таймера
#endif
#define IR_Transmitter_Timer_IRQHandler	TIM_IRQHandler (IRDA_TIMER)	// Установка названия прямого вектора прерывания таймера IRDA_TIMER
#endif

// Тайминги протокола NEC (в микросекундах)
#define NEC_LEAD_PULSE			9000	// 9 мс импульс (carrier)
#define NEC_LEAD_SPACE			4500	// 4.5 мс пауза
#define NEC_REPEAT_SPACE		2250	// 2.25 мс пауза в повторе
#define NEC_BIT_PULSE			560		// 0.56 мс импульс (carrier)
#define NEC_BIT_ZERO_SPACE		565		// 0.565 мс пауза для 0
#define NEC_BIT_ONE_SPACE		1690	// 1.69 мс пауза для 1
#define NEC_STOP_PULSE			560		// 0.56 мс стоп-импульс (для повтора)

// Частота несущей 38 кГц (период ~26.3 мкс)
#define IR_CARRIER_FREQ_HZ		38000U
#define IR_CARRIER_PERIOD_US	(1000000U / IR_CARRIER_FREQ_HZ)	// ~26 мкс
#define IR_CARRIER_HALF_PERIOD	(IR_CARRIER_PERIOD_US / 2)		// Полупериод для программного тоггла


// Объявление структуры данных:
typedef struct
{
	uint8_t mode;			// Режим работы генератора:
	/* 0 - не активен, 1 - стартовый импульс, 2 - стартовая пауза, 3 - бит импульс, 4 - бит пауза, 5 - стоп-импульс, 6 - пауза между кодами */
	uint32_t tx_code;		// 32-битный код для передачи (addr + ~addr + cmd + ~cmd)
	bool repeat_en;			// Разрешение автоповтора
	uint8_t bit_cnt;		// Счётчик битов (0..31)
	uint8_t repeat_cnt;		// Счётчик повторов (0 - бесконечно)
	uint16_t repeat_timer;	// Таймер отсчёта интервала автоповтора, мс
} IR_Trsmt_Data_Struct;		// Структура данных ИК-передатчика

extern IR_Trsmt_Data_Struct IR_Trsmt_Data;	// Подключение общей структуры данных в главную программу


/*** Набор функций драйвера *****************************************************************************************************************/

void IR_Transmitter_Init (void);				// Инициализация и настройка вывода и таймера для ИК-передатчика
void IR_Transmitter_Start (uint32_t address, uint32_t command, bool repeat_en, uint8_t repeat_cnt);	// Отправка кода NEC
void IR_Transmitter_Stop (void);				// Остановка генерации кода
void IR_Transmitter_Timer_IRQHandler (void);	// Обработчик прерываний таймера IRDA_TIMER


#endif /* IRDA_CODE_TRANSMITTER_H_ */
